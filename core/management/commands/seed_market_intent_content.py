class Command(BaseCommand):
    help = "Ensure a national library of high-intent landscaping guides without overwriting CMS edits."

    def handle(self, *args, **options):
        category, _ = BlogCategory.objects.get_or_create(
            slug="palm-landscaping-services",
            defaults={
                "name": "خدمات النخيل واللاندسكيب",
                "description": "أدلة عملية عن النخيل والحدائق والعشب والري والصيانة واتخاذ قرار التنفيذ.",
                "meta_title": "دليل النخيل واللاندسكيب في السعودية",
                "meta_description": "مقالات عملية عن تنسيق الحدائق والنخيل والعشب والري والأسعار والصيانة في السعودية.",
            },
        )
        tags = []
        for tag_name, tag_slug in [("نخيل", "palms"), ("لاندسكيب", "landscaping"), ("أشجار", "trees"), ("ري", "irrigation"), ("صيانة", "maintenance")]:
            tag, _ = BlogTag.objects.get_or_create(slug=tag_slug, defaults={"name": tag_name, "meta_title": tag_name, "meta_description": tag_name})
            tags.append(tag)

        created_posts = existing_posts = 0
        for index, (title, slug, keyword) in enumerate(ARTICLES, start=1):
            excerpt = f"دليل عملي عن {keyword} يساعدك على فهم الخيارات والتجهيز والصيانة والعوامل التي تؤثر على التنفيذ داخل السعودية."
            post, created = BlogPost.objects.get_or_create(
                slug=slug,
                defaults={
                    "title": title,
                    "excerpt": excerpt,
                    "content": build_article_content(title, keyword),
                    "category": category,
                    "status": "published",
                    "publish_at": timezone.now(),
                    "meta_title": f"{title} | نخيل نجد",
                    "meta_description": excerpt,
                    "meta_keywords": f"{keyword}, تنسيق حدائق, لاندسكيب, السعودية",
                    "is_featured": index <= 6,
                },
            )
            if created:
                post.tags.set(tags)
                created_posts += 1
            else:
                existing_posts += 1

        self.stdout.write(self.style.SUCCESS(f"market_articles_created={created_posts} existing={existing_posts} target={len(ARTICLES)}"))
