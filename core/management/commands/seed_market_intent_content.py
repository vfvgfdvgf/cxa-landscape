def _theme(title: str, keyword: str) -> str:
    text = f"{title} {keyword}"
    if any(token in text for token in ("سعر", "تكلفة", "عقد", "مقاول", "شركة")):
        return "commercial"
    if any(token in text for token in ("ري", "ماء", "تسرب", "تنقيط")):
        return "irrigation"
    if any(token in text for token in ("نخيل", "نخلة")):
        return "palm"
    if any(token in text for token in ("عشب", "ثيل", "مسطحات")):
        return "turf"
    if any(token in text for token in ("أشجار", "شجيرات", "نباتات", "زراعة", "تربة", "سماد", "آفات")):
        return "planting"
    return "landscape"


